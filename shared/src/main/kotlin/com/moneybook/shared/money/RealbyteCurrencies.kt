package com.moneybook.shared.money

import java.util.Locale

/** Realbyte 4.12.13's currency list (Main/Sub Currency Setting), measured on the realbyte_34 emulator. */
object RealbyteCurrencies {
    data class Entry(val code: String, val label: String) {
        /** "Czech" from "CZK - Czech (Kč)". */
        val name: String get() = label.substringAfter(" - ").substringBeforeLast("(").trim()
        val symbol: String get() = label.substringAfterLast("(").removeSuffix(")")
    }

    val all: List<Entry> = LABELS.trim().lines().map { Entry(it.take(3), it.trim()) }
    private val byCode = all.associateBy { it.code }

    fun find(code: String): Entry? = byCode[code.trim().uppercase()]

    /** Measured: the list's symbol (USD shows "US$" in the list but uses "$"), ISO decimals, Front except CZK. */
    fun defaultSpec(code: String): CurrencySpec {
        val upper = code.trim().uppercase()
        val symbol = when (upper) {
            "USD" -> "$"
            else -> find(upper)?.symbol
                ?: runCatching { java.util.Currency.getInstance(upper).getSymbol(Locale.ENGLISH) }.getOrNull()
                ?: upper
        }
        val position = if (upper == "CZK") SymbolPosition.END else SymbolPosition.START
        return CurrencySpec(upper, symbol, position, CurrencySpec.isoDecimals(upper))
    }
}

